#!/usr/bin/env python3
"""Build the Kiro 98 Games app: ui/index.mjs and assets/icon.png.

Embeds every games/*.html into the page module as a JSON string (so the
dashboard serves one .mjs and nothing else), and draws the original icons.
Stdlib only.

    python3 tools/build.py
"""

from __future__ import annotations

import json
import struct
import urllib.parse
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

GHOST = [
    "....KKKKKK....",
    "..KKWWWWWWKK..",
    ".KWWWWWWWWWWK.",
    ".KWWWWWWWWWWK.",
    "KWWWEEWWEEWWWK",
    "KWWWEEWWEEWWWK",
    "KWWWWWWWWWWWWK",
    "KWWWWWWWWWWWWK",
    "KWWWWWWWWWWWWK",
    "KWWWWWWWWWWWWK",
    "KWWWWWWWWWWWWK",
    "KWWWWWWWWWWWWK",
    "KWWKKWWWWKKWWK",
    "KWK..KWWK..KWK",
    "KK....KK....KK",
]
COLORS = {"K": "#0a0a0a", "W": "#ffffff", "E": "#0a0a0a"}

# Games shown on the desktop and in the Start menu, in order.
GAMES = [
    {"id": "solitaire", "title": "Solitaire", "file": "games/solitaire.html", "icon": "cards"},
]


def rects(rows: list[str], colors: dict[str, str], x0: int = 0, y0: int = 0) -> str:
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            n = 1
            while x + n < len(row) and row[x + n] == ch:
                n += 1
            if ch in colors:
                out.append(f'<rect x="{x0 + x}" y="{y0 + y}" width="{n}" height="1" fill="{colors[ch]}"/>')
            x += n
    return "".join(out)


def data_uri(svg: str) -> str:
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe="")


def ghost_svg() -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 14 15" shape-rendering="crispEdges">'
        + rects(GHOST, COLORS)
        + "</svg>"
    )


def cards_svg() -> str:
    # Two fanned cards: a ghost-backed card behind a heart card. 20x20 pixel grid.
    back = (
        '<rect x="1" y="1" width="11" height="15" fill="#0a0a0a"/>'
        '<rect x="2" y="2" width="9" height="13" fill="#ffffff"/>'
        '<rect x="3" y="3" width="7" height="11" fill="#000080"/>'
        '<rect x="5" y="6" width="3" height="3" fill="#ffffff"/>'
    )
    heart = [
        ".RR.RR.",
        "RRRRRRR",
        "RRRRRRR",
        ".RRRRR.",
        "..RRR..",
        "...R...",
    ]
    front = (
        '<rect x="7" y="4" width="12" height="15" fill="#0a0a0a"/>'
        '<rect x="8" y="5" width="10" height="13" fill="#ffffff"/>'
        + rects(heart, {"R": "#c00000"}, 10, 9)
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" shape-rendering="crispEdges">'
        + back + front + "</svg>"
    )


def icon_png(path: Path, size: int = 64) -> None:
    """Ghost on the teal desktop, 4x pixels, as an RGBA PNG."""
    teal = (0, 128, 128, 255)
    rgb = {"K": (10, 10, 10, 255), "W": (255, 255, 255, 255), "E": (10, 10, 10, 255)}
    scale = 4
    ox, oy = (size - 14 * scale) // 2, (size - 15 * scale) // 2
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            gx, gy = (x - ox) // scale, (y - oy) // scale
            px = teal
            if 0 <= gy < 15 and 0 <= gx < 14 and x >= ox and y >= oy:
                px = rgb.get(GHOST[gy][gx], teal)
            row += bytes(px)
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(png)


def main() -> None:
    manifest = json.loads((ROOT / "app.json").read_text())
    games = {
        g["id"]: {"title": g["title"], "icon": g["icon"], "html": (ROOT / g["file"]).read_text(encoding="utf-8")}
        for g in GAMES
    }
    page = (ROOT / "tools" / "page.template.mjs").read_text(encoding="utf-8")
    subs = {
        "/*@@GAMES@@*/ {}": json.dumps(games, ensure_ascii=False),
        "/*@@GHOST@@*/ ''": json.dumps(data_uri(ghost_svg())),
        "/*@@CARDS@@*/ ''": json.dumps(data_uri(cards_svg())),
        "/*@@VERSION@@*/ ''": json.dumps(manifest["version"]),
    }
    for marker, value in subs.items():
        if page.count(marker) != 1:
            raise SystemExit(f"template marker missing or repeated: {marker}")
        page = page.replace(marker, value)
    page = page.replace("// GENERATED into ui/index.mjs by tools/build.py; edit this template, not the output.",
                        "// GENERATED by tools/build.py from tools/page.template.mjs and games/*.html. Do not edit.")
    (ROOT / "ui").mkdir(exist_ok=True)
    (ROOT / "ui" / "index.mjs").write_text(page, encoding="utf-8")
    (ROOT / "assets").mkdir(exist_ok=True)
    icon_png(ROOT / "assets" / "icon.png")
    for p in ("ui/index.mjs", "assets/icon.png"):
        print(f"{p}  {(ROOT / p).stat().st_size} bytes")


if __name__ == "__main__":
    main()
